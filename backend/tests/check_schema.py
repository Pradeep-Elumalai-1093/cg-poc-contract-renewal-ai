"""
Database foundation check. Plain asserts, no framework:

    cd backend && python tests/check_schema.py

Needs a PostgreSQL server (see tests/pg.py). Creates throwaway databases,
migrates them with the real Alembic migration and then writes to the AI result
tables the way the AWS job will: plain INSERTs that omit the version columns.
"""
import os
import subprocess
import sys
import threading
import time
import uuid
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))
os.chdir(BACKEND)

import psycopg  # noqa: E402
from psycopg import errors  # noqa: E402
from psycopg.rows import dict_row  # noqa: E402
from sqlalchemy.engine import make_url  # noqa: E402

import pg  # noqa: E402

S = "ai_recommendations"
URL = pg.new_database()
DSN = make_url(URL).set(drivername="postgresql").render_as_string(hide_password=False)
os.environ.update(DATABASE_URL=URL, DATA_SOURCE="synthetic", AUTH_MODE="dev", SESSION_SECRET="x" * 40)


def conn(autocommit=True):
    return psycopg.connect(DSN, autocommit=autocommit, row_factory=dict_row)


def raises(exc, sql, *params):
    with conn() as c:
        try:
            c.execute(sql, params)
        except exc:
            return
        raise AssertionError(f"expected {exc.__name__} from: {sql[:80]}")


# ------------------------------------------------------------------ 1. UUIDv7
with conn() as c:
    ids = [r["u"] for r in c.execute("SELECT uuidv7() AS u FROM generate_series(1, 2000)")]
    assert len(set(ids)) == 2000, "uuidv7() produced duplicates"
    assert all(i.version == 7 for i in ids), "not all UUIDs are version 7"
    assert all(i.variant == uuid.RFC_4122 for i in ids)
    now_ms = time.time() * 1000
    assert all(abs(int(i.hex[:12], 16) - now_ms) < 10_000 for i in ids), "embedded timestamp is not 'now'"
    row = c.execute(f"INSERT INTO {S}.users (oid, email) VALUES ('o1', 'a@x.com') RETURNING id, status, role").fetchone()
    assert row["id"].version == 7 and row["status"] == "pending" and row["role"] == "user"  # server-side default id + defaults
print("ok - ids are UUIDv7 (version, variant, timestamp, uniqueness), generated by the database")

# ------------------------------------------------------------------ 2. version chain, all four tables
TABLES = [  # table, key column, version column, payload column
    ("contract_summary", "contractid", "ai_summary_version", "ai_summary"),
    ("account_summary", "accountid", "ai_summary_version", "ai_summary"),
    ("web_claims_summary", "contractid", "ai_summary_version", "ai_summary"),
    ("contract_recommendation", "contractid", "ai_recommendation_version", "ai_recommendation"),
]


def write(c, table, key, ver, payload, key_val, text, **extra):
    """A writer's INSERT: key, ctx and payload only - no id, prev_id, version or is_latest."""
    cols = {key: key_val, "ctx": "034", payload: text, **extra}
    names = ", ".join(cols)
    marks = ", ".join(["%s"] * len(cols))
    return c.execute(f"INSERT INTO {S}.{table} ({names}) VALUES ({marks}) RETURNING *", list(cols.values())).fetchone()


for table, key, ver, payload in TABLES:
    with conn() as c:
        v1 = write(c, table, key, ver, payload, "K1", "one")
        assert v1[ver] == 1 and v1["is_latest"] and v1["prev_id"] is None and v1["id"].version == 7
        assert v1["system"] == "ecare" and v1["language"] == "en" and v1["created_by"] == "pipeline"
        v2 = write(c, table, key, ver, payload, "K1", "two")
        v3 = write(c, table, key, ver, payload, "K1", "three")
        assert (v2[ver], v3[ver]) == (2, 3)
        assert v2["prev_id"] == v1["id"] and v3["prev_id"] == v2["id"], "version chain not linked"
        rows = c.execute(f"SELECT {ver}, is_latest FROM {S}.{table} WHERE {key} = 'K1' ORDER BY {ver}").fetchall()
        assert [(r[ver], r["is_latest"]) for r in rows] == [(1, False), (2, False), (3, True)], rows

        # other key / language / system are independent chains
        assert write(c, table, key, ver, payload, "K2", "x")[ver] == 1
        assert write(c, table, key, ver, payload, "K1", "fr", language="fr")[ver] == 1
        assert write(c, table, key, ver, payload, "K1", "sf", system="salesforce")[ver] == 1
        latest = c.execute(f"SELECT count(*) AS n FROM {S}.{table} WHERE {key} = 'K1' AND is_latest").fetchone()["n"]
        assert latest == 3, "expected one latest per (system, language)"  # en, fr, salesforce

        # the database itself refuses a second 'latest' or a duplicate version number
        raises(errors.UniqueViolation, f"UPDATE {S}.{table} SET is_latest = true WHERE id = %s", v1["id"])
        raises(errors.UniqueViolation, f"UPDATE {S}.{table} SET {ver} = 3 WHERE id = %s", v2["id"])

        # modified_on moves on UPDATE
        before = c.execute(f"SELECT modified_on FROM {S}.{table} WHERE id = %s", (v3["id"],)).fetchone()["modified_on"]
        time.sleep(0.02)
        c.execute(f"UPDATE {S}.{table} SET user_feedback = %s WHERE id = %s", (psycopg.types.json.Jsonb({"thumb": "up"}), v3["id"]))
        after = c.execute(f"SELECT modified_on, user_feedback FROM {S}.{table} WHERE id = %s", (v3["id"],)).fetchone()
        assert after["modified_on"] > before and after["user_feedback"] == {"thumb": "up"}
print("ok - all four tables: version chain, independent keys/languages/systems, latest uniqueness, modified_on")

# ------------------------------------------------------------------ 3. constraints
base = f"INSERT INTO {S}.contract_summary (contractid, ctx, ai_summary"
raises(errors.CheckViolation, base + ") VALUES ('C', '34', 'x')")                       # ctx must be 3 digits
raises(errors.CheckViolation, base + ") VALUES ('C', 'ABC', 'x')")
raises(errors.NotNullViolation, f"INSERT INTO {S}.contract_summary (contractid, ai_summary) VALUES ('C', 'x')")  # ctx required
raises(errors.NotNullViolation, f"INSERT INTO {S}.contract_summary (ctx, ai_summary) VALUES ('034', 'x')")       # key required
raises(errors.CheckViolation, base + ", system) VALUES ('C', '034', 'x', 'jde')")        # system must be known
rec = f"INSERT INTO {S}.contract_recommendation (contractid, ctx, "
raises(errors.CheckViolation, rec + "confidence) VALUES ('R', '034', 1.5)")
raises(errors.CheckViolation, rec + "action_status) VALUES ('R', '034', 'maybe')")
raises(errors.CheckViolation, rec + "outcome) VALUES ('R', '034', 'Won')")
print("ok - constraints reject a bad ctx, missing ctx or key, unknown system, confidence, action_status and outcome")

# ------------------------------------------------------------------ 4. recommendation specifics + JSONB
with conn() as c:
    j = psycopg.types.json.Jsonb
    r1 = c.execute(
        f"INSERT INTO {S}.contract_recommendation (contractid, ctx, ai_recommendation, retention_action_name, confidence, "
        "ai_configuration, input_data, input_hash, evaluation, draft_content) VALUES ('R9', '034', 'why', 'Service check-in', 0.82, %s, %s, %s, %s, %s) RETURNING *",
        (j({"model": "m1", "temperature": 0}), j({"risk": {"score": 71, "factors": [1, 2, {"a": None}]}}), "abc123",
         j({"composite": 8.1, "pass": True}), j({"email_subject": "Hello"}))).fetchone()
    assert r1["action_status"] == "Action required" and r1["outcome"] is None and float(r1["confidence"]) == 0.82
    assert r1["input_data"]["risk"]["factors"][2] == {"a": None} and r1["draft_content"] == {"email_subject": "Hello"}
    c.execute(f"UPDATE {S}.contract_recommendation SET outcome = 'Engaged', action_status = 'Action done' WHERE id = %s", (r1["id"],))
    r2 = write(c, "contract_recommendation", "contractid", "ai_recommendation_version", "ai_recommendation", "R9", "next milestone")
    old = c.execute(f"SELECT outcome, action_status FROM {S}.contract_recommendation WHERE id = %s", (r1["id"],)).fetchone()
    assert (old["outcome"], old["action_status"]) == ("Engaged", "Action done"), "older version lost its outcome"
    assert r2["outcome"] is None and r2["action_status"] == "Action required", "new version should start fresh"
print("ok - recommendation: JSONB round-trips; each version keeps its own status and outcome")

# ------------------------------------------------------------------ 5. concurrent writers
N = 12
errs, barrier = [], threading.Barrier(N)


def worker(i):
    try:
        with conn(autocommit=False) as c:
            barrier.wait()
            write(c, "contract_summary", "contractid", "ai_summary_version", "ai_summary", "RACE", f"w{i}")
            c.commit()
    except Exception as e:  # noqa: BLE001
        errs.append(repr(e))


threads = [threading.Thread(target=worker, args=(i,)) for i in range(N)]
[t.start() for t in threads]
[t.join() for t in threads]
assert not errs, errs
with conn() as c:
    rows = c.execute(f"SELECT id, prev_id, ai_summary_version AS v, is_latest FROM {S}.contract_summary WHERE contractid = 'RACE' ORDER BY ai_summary_version").fetchall()
    assert [r["v"] for r in rows] == list(range(1, N + 1)), [r["v"] for r in rows]
    assert [r["is_latest"] for r in rows] == [False] * (N - 1) + [True]
    assert all(rows[i]["prev_id"] == rows[i - 1]["id"] for i in range(1, N)), "chain broken under concurrency"
print(f"ok - {N} simultaneous writers for one key: versions 1..{N}, one latest, unbroken chain, no errors")

